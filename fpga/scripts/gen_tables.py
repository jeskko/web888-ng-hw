"""Generate ROM contents used by the RTL.

  rtl/gen/sincos_qw.mem   quarter-wave sine table for nco.v
  rtl/gen/rx_gain_rom.v   per-R2 normalisation (shift, gain) for rx_serial_cic.v

Run from the fpga/ directory:  python3 scripts/gen_tables.py
"""
import math
import os
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl", "gen")

# ---- NCO -------------------------------------------------------------------
NCO_ADDR_W = 10          # 1024-entry quarter wave
NCO_AMP = (1 << 17) - 8  # leaves room for the Taylor correction, 18-bit signed out


def gen_sincos():
    n = 1 << NCO_ADDR_W
    lines = []
    for i in range(n):
        # half-sample offset: entry i holds sin(2*pi*(i+0.5)/(4*n))
        v = round(NCO_AMP * math.sin(2 * math.pi * (i + 0.5) / (4 * n)))
        assert 0 < v < (1 << 17)
        lines.append(f"{v:05x}")
    with open(os.path.join(OUT, "sincos_qw.mem"), "w") as f:
        f.write("\n".join(lines) + "\n")


# ---- RX CIC2 gain normalisation -----------------------------------------------
# CIC2 input full scale (DC) is 2^31; CIC2 gain is R2^5.  Output target: 2^30.
#   ys  = y >>> sh1             (|ys| <= 2^23, fits the 25-bit DSP A port)
#   out = (ys * g) >>> 9        (g in [2^16, 2^17))
RX_N2 = 5
RX_IN_FS_LOG2 = 31
RX_OUT_FS_LOG2 = 30
RX_GAIN_SH2 = 9


def gen_rx_gain():
    rows = []
    for r2 in range(1, 64):
        fs = (1 << RX_IN_FS_LOG2) * r2 ** RX_N2
        sh1 = math.ceil(math.log2(fs)) - 23
        g = round((1 << (RX_GAIN_SH2 + RX_OUT_FS_LOG2 + sh1)) / fs)
        g = min(g, (1 << 17) - 1)
        assert (1 << 15) < g < (1 << 17), (r2, g)
        err_db = 20 * math.log10(g * fs / (1 << (RX_GAIN_SH2 + RX_OUT_FS_LOG2 + sh1)))
        rows.append((r2, sh1, g, err_db))
    with open(os.path.join(OUT, "rx_gain_rom.v"), "w") as f:
        f.write("// SPDX-License-Identifier: GPL-3.0-or-later\n")
        f.write("// generated by scripts/gen_tables.py -- do not edit\n")
        f.write("// R2 -> (sh1, g); RX output = ((y >>> sh1) * g) >>> 9\n")
        f.write("`timescale 1 ns / 1 ps\n`default_nettype none\n\n")
        f.write("module rx_gain_rom (\n  input  wire [5:0]  r2,\n"
                "  output reg  [5:0]  sh1,\n  output reg  [16:0] g\n);\n\n")
        f.write("  always @(*) begin\n    case (r2)\n")
        for r2, sh1, g, err in rows:
            f.write(f"      6'd{r2}: begin sh1 = 6'd{sh1}; g = 17'd{g}; end  // {err:+.5f} dB\n")
        f.write("      default: begin sh1 = 6'd0; g = 17'd0; end\n")
        f.write("    endcase\n  end\n\nendmodule\n\n`default_nettype wire\n")


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    gen_sincos()
    gen_rx_gain()
    print("tables written to", os.path.normpath(OUT), file=sys.stderr)
